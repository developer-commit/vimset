#!/bin/sh
# Lightweight Vim setup for macOS, Linux, and WSL. No root access required.
set -eu
umask 077

usage() {
    cat <<'HELP'
Usage: sh install.sh [--no-plugins] [--update] [--target-home PATH]

  --no-plugins        Install only vimrc and the local-settings example.
  --update            Update existing plugins with Git fast-forward only.
  --target-home PATH  Install for this home directory (default: $HOME).
  --help              Show this help.

Keep vimrc, plugins.tsv, and this script in the same directory.
Existing vimrc files are backed up before replacement. Existing plugins are
kept unless --update is given. Neither Vim nor language tools are installed.
HELP
}

die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }
say() { printf '%s\n' "$*"; }

install_plugins=1
update_plugins=0
target_home=${HOME:-}
while [ "$#" -gt 0 ]; do
    case "$1" in
        --no-plugins) install_plugins=0; shift ;;
        --update) update_plugins=1; shift ;;
        --target-home)
            [ "$#" -ge 2 ] && [ -n "$2" ] || die '--target-home needs a path.'
            target_home=$2
            shift 2
            ;;
        --help|-h) usage; exit 0 ;;
        *) die "Unknown option: $1 (use --help)." ;;
    esac
done
[ -n "$target_home" ] || die 'HOME is unset; pass --target-home PATH.'
[ "$install_plugins:$update_plugins" != 0:1 ] || die 'Do not combine --no-plugins and --update.'

script_dir=$(CDPATH= cd -P "$(dirname "$0")" && pwd)
source_vimrc=$script_dir/vimrc
manifest=$script_dir/plugins.tsv
[ -f "$source_vimrc" ] || die "Missing file: $source_vimrc"
[ -f "$manifest" ] || die "Missing file: $manifest"
if [ "$install_plugins" -eq 1 ]; then
    command -v git >/dev/null 2>&1 || die 'Git is missing from PATH. Install Git or use --no-plugins.'
fi

case "$target_home" in
    /*) ;;
    *) target_home=$(pwd)/$target_home ;;
esac
mkdir -p "$target_home"
target_home=$(CDPATH= cd -P "$target_home" && pwd)
vim_dir=$target_home/.vim
target_vimrc=$target_home/.vimrc
package_dir=$vim_dir/pack/lightvim/start
state_dir=$vim_dir/lightvim-state
backup_dir=''
stage_dir=''
temp_vimrc=''

cleanup() {
    # These paths are generated by mktemp in this invocation only.
    if [ -n "$temp_vimrc" ] && [ -f "$temp_vimrc" ]; then rm -f "$temp_vimrc"; fi
    if [ -n "$stage_dir" ] && [ -d "$stage_dir" ]; then rm -rf "$stage_dir"; fi
}
trap cleanup 0
trap 'exit 130' INT
trap 'exit 129' HUP
trap 'exit 143' TERM

ensure_backup() {
    if [ -z "$backup_dir" ]; then
        mkdir -p "$vim_dir/lightvim-backups"
        backup_dir=$(mktemp -d "$vim_dir/lightvim-backups/$(date -u '+%Y%m%dT%H%M%SZ').XXXXXX")
        printf 'Original config path: %s\n' "$target_vimrc" > "$backup_dir/RESTORE.txt"
    fi
}

quote_sh() {
    printf "'"
    printf '%s' "$1" | sed "s/'/'\\\\''/g"
    printf "'"
}

if [ -d "$target_vimrc" ] && [ ! -L "$target_vimrc" ]; then
    die "The config path is a directory: $target_vimrc"
fi
mkdir -p "$vim_dir"
vim_dir=$(CDPATH= cd -P "$vim_dir" && pwd)
package_dir=$vim_dir/pack/lightvim/start
state_dir=$vim_dir/lightvim-state
stage_dir=$(mktemp -d "$vim_dir/.lightvim-install.XXXXXX")
mkdir -p "$stage_dir/plugins" "$stage_dir/empty-hooks"
plan=$stage_dir/plan.tsv
: > "$plan"
tab=$(printf '\t')
cr=$(printf '\r')
seen_names='|'

if [ "$install_plugins" -eq 1 ]; then
    # Public repositories must not open an interactive credentials prompt.
    export GIT_TERMINAL_PROMPT=0
    while IFS="$tab" read -r plugin_name plugin_url plugin_branch extra || [ -n "$plugin_name$plugin_url$plugin_branch$extra" ]; do
        plugin_name=${plugin_name%"$cr"}
        case "$plugin_name" in ''|\#*) continue ;; esac
        plugin_branch=${plugin_branch%"$cr"}
        [ -z "$extra" ] || die "Too many fields in plugins.tsv: $plugin_name"
        case "$plugin_name" in
            .|..|-*|*[!A-Za-z0-9._-]*) die "Invalid plugin name: $plugin_name" ;;
        esac
        case "$seen_names" in *"|$plugin_name|"*) die "Duplicate plugin: $plugin_name" ;; esac
        seen_names=$seen_names$plugin_name'|'
        case "$plugin_url" in
            https://github.com/*/*.git) ;;
            *) die "Expected a GitHub HTTPS repository URL for $plugin_name." ;;
        esac
        case "$plugin_url" in *[!A-Za-z0-9:/._-]*) die "Invalid repository URL for $plugin_name." ;; esac
        case "$plugin_branch" in
            ''|-*|*[!A-Za-z0-9._/-]*) die "Invalid branch for $plugin_name." ;;
        esac

        destination=$package_dir/$plugin_name
        if [ -e "$destination" ] || [ -L "$destination" ]; then
            [ -d "$destination" ] || die "Plugin path is not a directory: $destination"
            if [ "$update_plugins" -eq 0 ]; then
                say "Keeping $plugin_name (use --update to update)."
                printf 'keep\t%s\t%s\t%s\n' "$plugin_name" "$plugin_url" "$plugin_branch" >> "$plan"
                continue
            fi
            [ ! -L "$destination" ] || die "Refusing to update a symlink: $destination"
            [ -d "$destination/.git" ] && [ ! -L "$destination/.git" ] || die "Update needs a standalone Git clone: $destination"
            if [ -e "$destination/.git/commondir" ] || [ -L "$destination/.git/commondir" ]; then
                die "Shared Git directories require manual updating: $plugin_name"
            fi
            actual_root=$(git -C "$destination" rev-parse --show-toplevel) || die "Invalid Git clone: $destination"
            [ "$actual_root" = "$destination" ] || die "Unexpected Git worktree root: $destination"
            actual_url=$(git -C "$destination" remote get-url origin) || die "Missing origin remote: $destination"
            [ "$actual_url" = "$plugin_url" ] || die "Origin differs from plugins.tsv: $plugin_name"
            actual_branch=$(git -C "$destination" symbolic-ref --quiet --short HEAD) || die "Detached HEAD; update manually: $plugin_name"
            [ "$actual_branch" = "$plugin_branch" ] || die "Branch differs from plugins.tsv: $plugin_name"
            worktree_override=$(git -C "$destination" config --local --get core.worktree || :)
            [ -z "$worktree_override" ] || die "A custom core.worktree requires manual updating: $plugin_name"
            tracked_changes=$(git -C "$destination" status --porcelain --untracked-files=no) || die "Could not inspect: $plugin_name"
            [ -z "$tracked_changes" ] || die "Tracked local edits found; leaving $plugin_name unchanged."
            say "Preparing update: $plugin_name"
            # Preserve untracked theme caches and user files. Never update the
            # live checkout until every network operation has succeeded.
            cp -RpP "$destination" "$stage_dir/plugins/$plugin_name"
            git -c core.hooksPath="$stage_dir/empty-hooks" -C "$stage_dir/plugins/$plugin_name" \
                pull --ff-only --no-rebase origin "$plugin_branch" || \
                die "Could not prepare $plugin_name; active plugins and vimrc were kept."
            old_commit=$(git -C "$destination" rev-parse HEAD)
            new_commit=$(git -C "$stage_dir/plugins/$plugin_name" rev-parse HEAD)
            if [ "$old_commit" = "$new_commit" ]; then
                printf 'keep\t%s\t%s\t%s\n' "$plugin_name" "$plugin_url" "$plugin_branch" >> "$plan"
                say "Already current: $plugin_name"
            else
                printf 'update\t%s\t%s\t%s\n' "$plugin_name" "$plugin_url" "$plugin_branch" >> "$plan"
            fi
        else
            say "Preparing plugin: $plugin_name"
            git -c core.hooksPath="$stage_dir/empty-hooks" clone --depth 1 --single-branch \
                --branch "$plugin_branch" -- "$plugin_url" "$stage_dir/plugins/$plugin_name" || \
                die "Could not download $plugin_name; active plugins and vimrc were kept."
            printf 'new\t%s\t%s\t%s\n' "$plugin_name" "$plugin_url" "$plugin_branch" >> "$plan"
        fi
    done < "$manifest"
    [ -s "$plan" ] || die 'plugins.tsv contains no plugin entries.'
fi

mkdir -p "$state_dir/undo" "$state_dir/swap" "$state_dir/backup"
# Only kit-owned state directories are adjusted; other Vim files are untouched.
chmod 700 "$state_dir" "$state_dir/undo" "$state_dir/swap" "$state_dir/backup"

# Stage the config beside its final path for a same-filesystem replacement.
config_changed=1
if [ -f "$target_vimrc" ] && cmp -s "$source_vimrc" "$target_vimrc"; then
    config_changed=0
else
    temp_vimrc=$(mktemp "$target_home/.lightvim-vimrc.XXXXXX")
    cp "$source_vimrc" "$temp_vimrc"
fi

if [ "$install_plugins" -eq 1 ]; then
    mkdir -p "$package_dir"
    while IFS="$tab" read -r action plugin_name plugin_url plugin_branch; do
        destination=$package_dir/$plugin_name
        case "$action" in
            update)
                ensure_backup
                mkdir -p "$backup_dir/plugins"
                mv "$destination" "$backup_dir/plugins/$plugin_name"
                if ! mv "$stage_dir/plugins/$plugin_name" "$destination"; then
                    mv "$backup_dir/plugins/$plugin_name" "$destination" || \
                        say "Restore the plugin manually from: $backup_dir/plugins/$plugin_name"
                    die "Could not activate $plugin_name; vimrc was not replaced."
                fi
                say "Updated $plugin_name"
                ;;
            new)
                mv "$stage_dir/plugins/$plugin_name" "$destination"
                say "Installed $plugin_name"
                ;;
        esac
    done < "$plan"
fi

if [ "$config_changed" -eq 1 ]; then
    if [ -e "$target_vimrc" ] || [ -L "$target_vimrc" ]; then
        ensure_backup
        # Moving the path preserves a symlink itself, never its target.
        mv "$target_vimrc" "$backup_dir/vimrc.previous"
    fi
    if ! mv "$temp_vimrc" "$target_vimrc"; then
        if [ -n "$backup_dir" ] && { [ -e "$backup_dir/vimrc.previous" ] || [ -L "$backup_dir/vimrc.previous" ]; }; then
            mv "$backup_dir/vimrc.previous" "$target_vimrc" || \
                say "Restore the config manually from: $backup_dir/vimrc.previous"
        fi
        die 'Could not activate vimrc.'
    fi
    temp_vimrc=''
    say "Installed config: $target_vimrc"
else
    say "Config already matches: $target_vimrc"
fi

example_path=$target_home/.vimrc.local.example
if [ -f "$script_dir/vimrc.local.example" ] && [ ! -e "$example_path" ] && [ ! -L "$example_path" ]; then
    cp "$script_dir/vimrc.local.example" "$example_path" || \
        say 'NOTE: Config installed, but the local-settings example could not be copied.'
fi

if [ "$install_plugins" -eq 1 ]; then
    revisions=$stage_dir/revisions.tsv
    printf '# name\tcommit\tconfigured repository\n' > "$revisions"
    while IFS="$tab" read -r action plugin_name plugin_url plugin_branch; do
        if [ -e "$package_dir/$plugin_name/.git" ]; then
            revision=$(git -C "$package_dir/$plugin_name" rev-parse HEAD 2>/dev/null || printf 'unmanaged')
        else
            revision=unmanaged
        fi
        printf '%s\t%s\t%s\n' "$plugin_name" "$revision" "$plugin_url" >> "$revisions"
    done < "$plan"
    # Rename instead of writing through a pre-existing symlink.
    if [ -d "$vim_dir/lightvim-plugin-revisions.tsv" ]; then
        say 'NOTE: Config installed; a directory at the revision-log path was left unchanged.'
    else
        mv "$revisions" "$vim_dir/lightvim-plugin-revisions.tsv" || \
            say 'NOTE: Config installed, but the plugin revision log could not be saved.'
    fi
fi

say ''
say 'Ready. Restart Vim; run :LightVimHealth to inspect the setup.'
if [ "$install_plugins" -eq 1 ]; then
    say 'For plugin help, run :helptags ALL once.'
fi
say "Optional personal settings: $target_home/.vimrc.local"
if [ -n "$backup_dir" ]; then
    say "Backup: $backup_dir"
    if [ -e "$backup_dir/vimrc.previous" ] || [ -L "$backup_dir/vimrc.previous" ]; then
        printf 'Restore previous config: mv '
        quote_sh "$backup_dir/vimrc.previous"
        printf ' '
        quote_sh "$target_vimrc"
        printf '\n'
    fi
    if [ -d "$backup_dir/plugins" ]; then
        say 'Previous plugin versions are in the backup/plugins directory.'
    fi
fi
if ! command -v vim >/dev/null 2>&1; then
    say 'NOTE: vim is not on PATH. Install full Vim 8.2+ (9.x recommended), then reopen the terminal.'
fi
if [ -n "${VIMINIT:-}" ]; then
    say 'NOTE: VIMINIT is set; it can bypass the installed vimrc. Check :echo $MYVIMRC in Vim.'
fi
